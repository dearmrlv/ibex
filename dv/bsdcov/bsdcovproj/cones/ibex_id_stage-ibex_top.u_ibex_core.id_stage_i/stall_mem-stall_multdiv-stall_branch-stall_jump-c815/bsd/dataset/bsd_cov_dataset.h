static constexpr bool BSD_COV_OUTPUT_MAJORITY[PO_WIDTH] = {
  false, false, false, false
};

static std::atomic<long long> bsd_cov_empty_left_branches{0};
static std::atomic<long long> bsd_cov_empty_right_branches{0};
static std::atomic<long long> bsd_cov_fallback_left_outputs{0};
static std::atomic<long long> bsd_cov_fallback_right_outputs{0};
static std::atomic<long long> bsd_cov_total_branch_replay_calls{0};

static inline bool bsd_cov_get_bit(const uint64_t* words, int64_t bit) {
    return (words[bit / 64] >> (bit % 64)) & 1ULL;
}

static inline bool bsd_cov_train_input_bit(int64_t sample_id, int64_t bit) {
    return bsd_cov_get_bit(BSD_COV_TRAIN_INPUTS[sample_id], bit);
}

static inline bool bsd_cov_train_output_bit(int64_t sample_id, int64_t bit) {
    return bsd_cov_get_bit(BSD_COV_TRAIN_OUTPUTS[sample_id], bit);
}

static inline bool bsd_cov_eval_input_bit(int64_t sample_id, int64_t bit) {
    return bsd_cov_get_bit(BSD_COV_EVAL_INPUTS[sample_id], bit);
}

static inline bool bsd_cov_eval_output_bit(int64_t sample_id, int64_t bit) {
    return bsd_cov_get_bit(BSD_COV_EVAL_OUTPUTS[sample_id], bit);
}

static inline bool bsd_cov_prefix_match(
    int64_t sample_id,
    const bool* node_mask,
    const int64_t* variable_order,
    int64_t depth
) {
    for (int64_t d = 0; d < depth; ++d) {
        int64_t bit = variable_order[d];
        if (bsd_cov_train_input_bit(sample_id, bit) != node_mask[bit]) return false;
    }
    return true;
}

static inline void bsd_cov_fill_branch_outputs(
    const bool* node_mask,
    const int64_t* variable_order,
    int64_t depth,
    int64_t split_bit,
    int64_t output_bit,
    int64_t sample_count,
    bool* left_outputs,
    bool* right_outputs
) {
    bsd_cov_total_branch_replay_calls.fetch_add(1, std::memory_order_relaxed);
    std::vector<int64_t> left_ids;
    std::vector<int64_t> right_ids;
    left_ids.reserve(BSD_COV_NUM_TRAIN_SAMPLES);
    right_ids.reserve(BSD_COV_NUM_TRAIN_SAMPLES);
    for (int64_t s = 0; s < BSD_COV_NUM_TRAIN_SAMPLES; ++s) {
        if (!bsd_cov_prefix_match(s, node_mask, variable_order, depth)) continue;
        if (bsd_cov_train_input_bit(s, split_bit)) right_ids.push_back(s);
        else left_ids.push_back(s);
    }
    bool fallback = BSD_COV_OUTPUT_MAJORITY[output_bit];
    if (left_ids.empty()) {
        bsd_cov_empty_left_branches.fetch_add(1, std::memory_order_relaxed);
        bsd_cov_fallback_left_outputs.fetch_add(sample_count, std::memory_order_relaxed);
        for (int64_t i = 0; i < sample_count; ++i) left_outputs[i] = fallback;
    } else {
        for (int64_t i = 0; i < sample_count; ++i) left_outputs[i] = bsd_cov_train_output_bit(left_ids[i % left_ids.size()], output_bit);
    }
    if (right_ids.empty()) {
        bsd_cov_empty_right_branches.fetch_add(1, std::memory_order_relaxed);
        bsd_cov_fallback_right_outputs.fetch_add(sample_count, std::memory_order_relaxed);
        for (int64_t i = 0; i < sample_count; ++i) right_outputs[i] = fallback;
    } else {
        for (int64_t i = 0; i < sample_count; ++i) right_outputs[i] = bsd_cov_train_output_bit(right_ids[i % right_ids.size()], output_bit);
    }
}

static inline int64_t bsd_cov_exact_lookup(const bool* input_data) {
    for (int64_t s = 0; s < BSD_COV_NUM_TRAIN_SAMPLES; ++s) {
        bool match = true;
        for (int64_t b = 0; b < PI_WIDTH; ++b) {
            if (bsd_cov_train_input_bit(s, b) != input_data[b]) {
                match = false;
                break;
            }
        }
        if (match) return s;
    }
    return -1;
}

static inline bool* io_generator_outer(bool* input_data, bool* output_data) {
    int64_t sid = bsd_cov_exact_lookup(input_data);
    for (int64_t b = 0; b < PO_WIDTH; ++b) {
        output_data[b] = (sid >= 0) ? bsd_cov_train_output_bit(sid, b) : BSD_COV_OUTPUT_MAJORITY[b];
    }
    return output_data;
}

static inline void bsd_cov_write_replay_stats(const char* path) {
    std::ofstream out(path);
    out << "{\n";
    out << "  \"total_branch_replay_calls\": " << bsd_cov_total_branch_replay_calls.load() << ",\n";
    out << "  \"empty_left_branches\": " << bsd_cov_empty_left_branches.load() << ",\n";
    out << "  \"empty_right_branches\": " << bsd_cov_empty_right_branches.load() << ",\n";
    out << "  \"fallback_left_outputs\": " << bsd_cov_fallback_left_outputs.load() << ",\n";
    out << "  \"fallback_right_outputs\": " << bsd_cov_fallback_right_outputs.load() << "\n";
    out << "}\n";
}
